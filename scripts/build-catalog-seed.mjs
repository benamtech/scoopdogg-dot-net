// Generate migrations/004_catalog_seed.sql from the TypeScript content modules.
//
//   node --experimental-strip-types scripts/build-catalog-seed.mjs
//
// The 11 services, their full rate card, 16 cities, 6 articles and 18 reviews are the
// most valuable thing Josue owns and they currently live in TypeScript arrays inside a
// bundle. This lifts them into the catalog tables so that from then on, adding a service
// or raising a price is something he does in the admin.
//
// Generated, not hand-written, so it can be re-run and diffed against the source.
import { writeFileSync } from 'node:fs';
import { SERVICES } from '../migrations/seed-source/services.ts';
import { CITIES } from '../migrations/seed-source/cities.ts';
import { FEATURED_REVIEWS, MORE_REVIEWS } from '../migrations/seed-source/reviews.ts';
import { ARTICLES } from '../src/lib/articles.ts';

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return "'" + String(v).replaceAll("'", "''") + "'";
};
const arr = (a) => a?.length
  ? 'ARRAY[' + a.map(q).join(', ') + ']::text[]'
  : "'{}'::text[]";
const json = (o) => q(JSON.stringify(o ?? [])) + '::jsonb';

// "$15/week" -> {cents: 1500, suffix: '/week'} ; "Custom quote" -> quote
// "$50+"     -> {cents: 5000, suffix: '+'}     ; "From $40/visit" -> {4000, '/visit'}
function parsePrice(raw) {
  const s = String(raw).trim();
  if (/custom|quote/i.test(s)) return { cents: null, suffix: '', quote: true, from: false };
  const m = s.match(/\$\s*([\d,]+(?:\.\d{2})?)/);
  if (!m) return { cents: null, suffix: '', quote: true, from: false };
  const cents = Math.round(parseFloat(m[1].replace(/,/g, '')) * 100);
  let suffix = s.slice(s.indexOf(m[0]) + m[0].length).trim();
  // "From $40/visit" and "$50+" both mean a floor, not a quote.
  const from = /^from/i.test(s) || suffix.startsWith('+');
  if (suffix.startsWith('+')) suffix = suffix.slice(1).trim();
  return { cents, suffix, quote: false, from };
}

// "2 dogs" -> 2..2 ; "4+ dogs" -> 4..null ; "Medium area (200-500 sq ft)" -> 200..500
// "Small area (under 200 sq ft)" -> null..200 ; "500+ sq ft" -> 500..null
function parseQty(label) {
  const range = label.match(/(\d[\d,]*)\s*[-–]\s*(\d[\d,]*)/);
  if (range) return [+range[1].replace(/,/g,''), +range[2].replace(/,/g,'')];
  const under = label.match(/under\s+(\d[\d,]*)/i);
  if (under) return [null, +under[1].replace(/,/g,'')];
  const plus = label.match(/(\d[\d,]*)\s*\+/);
  if (plus) return [+plus[1].replace(/,/g,''), null];
  const one = label.match(/(\d[\d,]*)/);
  if (one) { const n = +one[1].replace(/,/g,''); return [n, n]; }
  return [null, null];
}

// Inferring the basis from label text alone gets two services wrong, so the ambiguous
// ones are named explicitly. `one-time-dog-poop-cleanup` reads as 'dogs' because one
// label happens to say "or multiple dogs", but its tiers are WEEKS OF BUILDUP - asking
// "how many dogs?" would have quoted a 2-dog customer $99 and a 4-dog customer $149 off
// a question that has nothing to do with the price.
const BASIS_OVERRIDE = {
  'one-time-dog-poop-cleanup': 'choice',   // standard / heavy / severe buildup
  'weekly-yard-maintenance':   'choice',   // small / medium / large yard
};
function basisFor(slug, labels) {
  if (BASIS_OVERRIDE[slug]) return BASIS_OVERRIDE[slug];
  const j = labels.join(' ').toLowerCase();
  if (/sq ft/.test(j)) return 'sqft';
  if (/litter box/.test(j)) return 'boxes';
  if (/litter-robot/.test(j)) return 'units';
  if (/level/.test(j)) return 'levels';
  if (/\bdogs?\b/.test(j)) return 'dogs';
  return 'flat';
}
const BASIS_LABEL = {
  dogs: 'How many dogs?', sqft: 'Roughly how big is the area, in square feet?',
  boxes: 'How many litter boxes?', units: 'How many units?',
  levels: 'How many levels?', choice: 'Which best describes it?', flat: '',
};

const out = [
  '-- Scoop Dogg - seed the catalog from the content that already exists.',
  '--',
  '-- GENERATED by scripts/build-catalog-seed.mjs. Do not hand-edit; regenerate.',
  '-- Source: migrations/seed-source/{services,cities,reviews}.ts - the content as Josue published',
  '-- it before the rebuild. FROZEN. The database is the source now, and migrations 013 and 014',
  '-- have moved the prices since: RE-RUNNING THIS WOULD OVERWRITE THEM WITH THE OLD ONES.',
  '--',
  '-- After this runs, the rate card is data. Raising a price is an UPDATE in the admin,',
  '-- not a pull request, and it does not touch a single existing subscription.',
  '',
  'begin;',
  '',
];

let tierCount = 0;
for (const [i, s] of SERVICES.entries()) {
  const labels = s.pricing.map(p => p.label);
  const basis = basisFor(s.slug, labels);
  out.push(`insert into services (slug, name, short_name, kind, price_basis, basis_label, pricing_note, sort_order, status, meta_title, meta_description, h1, intro, what_includes, who_its_for, faqs, related_slugs) values (`);
  out.push(`  ${q(s.slug)}, ${q(s.name)}, ${q(s.shortName)}, ${q(/weekly/.test(s.slug) ? 'recurring' : 'one_time')}, ${q(basis)}, ${q(BASIS_LABEL[basis])}, ${q(s.pricingNote)}, ${(i + 1) * 10}, 'active',`);
  out.push(`  ${q(s.metaTitle)}, ${q(s.metaDescription)}, ${q(s.h1)}, ${q(s.intro)}, ${arr(s.whatIncludes)}, ${q(s.whoItsFor)}, ${json(s.faqs)}, ${arr(s.relatedSlugs)});`);
  for (const [j, p] of s.pricing.entries()) {
    const { cents, suffix, quote, from } = parsePrice(p.price);
    // A 'choice' tier is picked by its label, so a parsed quantity would be noise at best
    // and a wrong bracket at worst.
    const [min, max] = basis === 'choice' ? [null, null] : parseQty(p.label);
    tierCount++;
    out.push(`insert into service_tiers (service_slug, label, min_qty, max_qty, price_cents, price_suffix, requires_quote, price_is_from, sort_order) values (${q(s.slug)}, ${q(p.label)}, ${q(min)}, ${q(max)}, ${q(cents)}, ${q(suffix)}, ${quote ? 'true' : 'false'}, ${from ? 'true' : 'false'}, ${(j + 1) * 10});`);
  }
  out.push('');
}

for (const [i, c] of CITIES.entries()) {
  out.push(`insert into service_areas (slug, name, county, state, tier, bookable, market, neighborhoods, nearby_slugs, meta_title, meta_description, intro, local_context, faqs, sort_order, status) values (${q(c.slug)}, ${q(c.name)}, ${q(c.region === 'ventura-county' ? 'Ventura' : null)}, 'CA', ${c.tier}, true, ${q(c.region)}, ${arr(c.neighborhoods)}, ${arr(c.nearbySlug)}, ${q(c.metaTitle)}, ${q(c.metaDescription)}, ${q(c.intro)}, ${q(c.localContext)}, ${json(c.faqs)}, ${(i + 1) * 10}, 'active');`);
}
out.push('');

// BOTH arrays. reviews.ts exports FEATURED_REVIEWS (11) and MORE_REVIEWS (7); an
// earlier version of this script imported only the first and silently dropped seven
// real customer reviews. `featured` is what the distinction becomes.
const ALL_REVIEWS = [
  ...FEATURED_REVIEWS.map(r => ({ ...r, featured: true })),
  ...MORE_REVIEWS.map(r => ({ ...r, featured: false })),
];
for (const [i, r] of ALL_REVIEWS.entries()) {
  out.push(`insert into reviews (id, author_name, author_badge, quote, rating, source, source_url, reviewed_on, featured, sort_order) values (${q(r.id)}, ${q(r.name)}, ${q(r.reviewerBadge ?? null)}, ${q(r.quote)}, ${q(null)}, 'google', ${q(r.googleUrl)}, ${q(r.date)}, ${r.featured ? 'true' : 'false'}, ${(i + 1) * 10});`);
}

// The 6 resource articles. `body` keeps the whole section structure as jsonb so the
// renderer and the admin editor read the same shape.
for (const a of ARTICLES) {
  out.push(`insert into articles (slug, title, meta_title, meta_description, body, sources, published_at, status) values (${q(a.slug)}, ${q(a.title)}, ${q(a.metaTitle)}, ${q(a.metaDescription)}, ${json({ excerpt: a.excerpt, openingAnswer: a.openingAnswer, readTime: a.readTime, heroImage: a.heroImage, tags: a.tags, sections: a.sections, faqs: a.faqs })}, ${json(a.sections?.flatMap(s => s.sources ?? []) ?? [])}, ${q(a.publishedDate)}::timestamptz, 'active');`);
}
out.push('');

out.push('', '-- The seed is wrong unless every row landed.', 'do $$', 'declare s int; t int; a int; r int; ar int;', 'begin',
  '  select count(*) into s from services;',
  '  select count(*) into t from service_tiers;',
  '  select count(*) into a from service_areas;',
  '  select count(*) into r from reviews;',
  '  select count(*) into ar from articles;',
  `  if s <> ${SERVICES.length} then raise exception 'expected ${SERVICES.length} services, found %', s; end if;`,
  `  if t <> ${tierCount} then raise exception 'expected ${tierCount} tiers, found %', t; end if;`,
  `  if a <> ${CITIES.length} then raise exception 'expected ${CITIES.length} areas, found %', a; end if;`,
  `  if r <> ${ALL_REVIEWS.length} then raise exception 'expected ${ALL_REVIEWS.length} reviews, found %', r; end if;`,
  `  if ar <> ${ARTICLES.length} then raise exception 'expected ${ARTICLES.length} articles, found %', ar; end if;`,
  'end $$;', '', 'commit;', '');

writeFileSync(new URL('../migrations/004_catalog_seed.sql', import.meta.url), out.join('\n'));
console.log(`wrote 004_catalog_seed.sql — ${SERVICES.length} services, ${tierCount} tiers, ${CITIES.length} areas, ${ALL_REVIEWS.length} reviews, ${ARTICLES.length} articles`);
