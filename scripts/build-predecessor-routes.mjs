/**
 * Freeze what the PREDECESSOR site served into a file the build can read.
 *
 *   node scripts/build-predecessor-routes.mjs [commit-ish]
 *
 * The rebuild dropped six admin routes, a 301, and 71 sitemap URLs, and each was found
 * by hand. The gate that stops it recurring needs the old route table — but the build
 * that runs the gate happens on Vercel from an uploaded tarball with no git history, so
 * the gate cannot shell out to git. It reads this snapshot instead.
 *
 * A snapshot can rot, so it records the commit it came from and the gate re-derives
 * from that exact commit whenever git is available, requiring zero difference. Never
 * hand-edit gates/predecessor-routes.json; re-run this.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const ref = process.argv[2] || 'HEAD';
const sha = execFileSync('git', ['rev-parse', ref], { encoding: 'utf8' }).trim();

export function derive(commit) {
  const show = (p) => {
    try { return execFileSync('git', ['show', `${commit}:${p}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }); }
    catch { return null; }
  };
  const app = show('src/App.tsx') || '';
  const redirects = show('public/_redirects') || '';
  const sitemap = show('public/sitemap.xml') || '';

  const staticRoutes = [], dynamicRoutes = [];
  for (const m of app.matchAll(/\bpath="(\/[^"]*)"/g)) {
    (m[1].includes(':') ? dynamicRoutes : staticRoutes).push(m[1]);
  }
  const redirectSources = [];
  for (const line of redirects.split('\n')) {
    const from = line.trim().split(/\s+/)[0];
    if (from && from.startsWith('/') && !from.includes('*')) redirectSources.push(from);
  }
  const sitemapPaths = [];
  for (const m of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    sitemapPaths.push(new URL(m[1]).pathname.replace(/\/$/, '') || '/');
  }
  const uniq = (a) => [...new Set(a)].sort();
  return {
    staticRoutes: uniq(staticRoutes),
    dynamicRoutes: uniq(dynamicRoutes),
    redirectSources: uniq(redirectSources),
    sitemapPaths: uniq(sitemapPaths),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const routes = derive(sha);
  const total = routes.staticRoutes.length + routes.redirectSources.length + routes.sitemapPaths.length;
  if (!total) {
    console.error(`nothing found at ${sha} — src/App.tsx, public/_redirects and public/sitemap.xml are all absent there`);
    process.exit(1);
  }
  const out = {
    _: 'Generated by scripts/build-predecessor-routes.mjs. Do not hand-edit.',
    commit: sha,
    from: ['src/App.tsx', 'public/_redirects', 'public/sitemap.xml'],
    ...routes,
  };
  writeFileSync('gates/predecessor-routes.json', JSON.stringify(out, null, 2) + '\n');
  console.log(`gates/predecessor-routes.json — ${sha.slice(0, 8)}: ` +
    `${routes.staticRoutes.length} static, ${routes.dynamicRoutes.length} dynamic, ` +
    `${routes.redirectSources.length} redirect source(s), ${routes.sitemapPaths.length} sitemap URL(s)`);
}
